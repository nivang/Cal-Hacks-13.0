-- Per user onboarding: the people who sign in, their magic links, and the OAuth server their AI app connects through.
--
-- users: one row per person. The uuid id also names the user's own CDP server account (it fits CDP's 2 to 36
-- character rule and can never be the shared "sentinel" account). agent_id and wallet_address are set together, in
-- one transaction, when the first sign in creates the wallet, so a user has both or neither, and no two users can
-- share an agent or a wallet (addresses compare case insensitively).
-- agents.cash_account_id: each user's agent books to its own cash account (1010-<agent id>). Null keeps the shared
-- 1010 USDC Cash for the agents from before sign in (research-agent, the demo). Unique, so no two agents share one.
-- magic_links, oauth_codes, oauth_tokens: every link, code and token is stored only as an HMAC, never in the clear.
-- oauth_codes: one row per approved consent. It holds the code, then serves as the grant its tokens belong to, so
-- revoking it stops every token of the grant at once. oauth_clients stores no secret: it is derived from the id.
-- The indexes serve the rate limits (rows counted per address, per IP and overall within a time window), the purge
-- of old rows, foreign key checks, and the per agent price history the guard reads (attempts.load_history).
-- Default deny, as in 004 and 006: RLS on and every grant revoked for the five new tables and their identity
-- sequences (Supabase grants anon and authenticated usage and setval on new sequences by default). The one new
-- grant lets dashboard viewers (005) read agents.cash_account_id.

create table users (
    id uuid primary key default gen_random_uuid(),                          -- also the user's CDP account name
    email text not null check (length(email) <= 254),                       -- where mail goes
    email_key text not null unique check (email_key = lower(email_key)),    -- lookup key
    agent_id bigint unique references agents (id),                          -- set with the wallet, in one transaction
    wallet_address text check (wallet_address ~ '^0x[0-9a-fA-F]{40}$'),
    wallet_created_at timestamptz,
    session_epoch integer not null default 0,                               -- bumped by "sign out everywhere"
    created_at timestamptz not null default now(),
    last_sign_in_at timestamptz,
    check ((agent_id is null) = (wallet_address is null))
);
create unique index users_wallet_address_key on users (lower(wallet_address)) where wallet_address is not null;

alter table agents add column cash_account_id bigint references accounts (id);  -- null: the shared 1010
create unique index agents_cash_account_key on agents (cash_account_id) where cash_account_id is not null;
grant select (cash_account_id) on agents to authenticated;                       -- dashboard viewers, as in 005

create table magic_links (
    id bigint generated by default as identity primary key,
    token_hash text not null unique,
    email text not null,
    email_key text not null,
    limit_key text not null,                        -- email_key without +tag (and gmail dots): rate limits only
    ip_hash text not null,                          -- HMAC of the IP (IPv6 by /64), never the IP
    next_path text check (next_path is null or (next_path like '/%' and next_path not like '//%')),
    created_at timestamptz not null default now(),
    expires_at timestamptz not null,                -- 15 minutes
    used_at timestamptz,                            -- set once, atomically
    check (expires_at > created_at)
);
create index magic_links_limit_key_created_idx on magic_links (limit_key, created_at);
create index magic_links_ip_created_idx on magic_links (ip_hash, created_at);
create index magic_links_created_idx on magic_links (created_at);

create table oauth_clients (
    client_id text primary key,                                             -- DCR uuid; text so CIMD URLs fit later
    metadata jsonb not null check (octet_length(metadata::text) <= 4096),   -- allowlisted fields, never a secret
    token_endpoint_auth_method text not null
        check (token_endpoint_auth_method in ('none', 'client_secret_post', 'client_secret_basic')),
    created_ip_hash text not null,
    created_at timestamptz not null default now(),
    last_used_at timestamptz                                                -- never used clients go after 30 days
);
create index oauth_clients_ip_created_idx on oauth_clients (created_ip_hash, created_at);
create index oauth_clients_created_idx on oauth_clients (created_at);

create table oauth_codes (                          -- one approved consent: the code, then the grant
    id bigint generated by default as identity primary key,
    code_hash text not null unique,
    request_nonce text not null unique,             -- one code per consent request
    client_id text not null references oauth_clients (client_id) on delete cascade,
    user_id uuid not null references users (id),
    redirect_uri text not null,
    redirect_uri_provided_explicitly boolean not null,
    code_challenge text not null,
    scopes text[] not null,
    resource text not null,
    created_at timestamptz not null default now(),
    expires_at timestamptz not null,                -- the code: 5 minutes
    used_at timestamptz,                            -- the code was exchanged
    grant_expires_at timestamptz not null,          -- 90 days: no token outlives it
    revoked_at timestamptz                          -- grant revoked: all its tokens stop
);
create index oauth_codes_user_idx on oauth_codes (user_id);
create index oauth_codes_client_idx on oauth_codes (client_id);

create table oauth_tokens (
    id bigint generated by default as identity primary key,
    token_hash text not null unique,
    kind text not null check (kind in ('access', 'refresh')),
    grant_id bigint not null references oauth_codes (id) on delete cascade,
    created_at timestamptz not null default now(),
    expires_at timestamptz not null,
    used_at timestamptz,                            -- refresh only: when it was rotated
    check (kind = 'refresh' or used_at is null)
);
create index oauth_tokens_grant_idx on oauth_tokens (grant_id);
create index oauth_tokens_expires_idx on oauth_tokens (expires_at);

-- The price jump baseline is per agent: load_history reads this agent's last settled prices from one seller.
create index payment_attempts_agent_pay_to_settled_idx on payment_attempts (agent_id, lower(pay_to), settled_at desc)
    where status = 'settled';

alter table users enable row level security;
alter table magic_links enable row level security;
alter table oauth_clients enable row level security;
alter table oauth_codes enable row level security;
alter table oauth_tokens enable row level security;

revoke all on users, magic_links, oauth_clients, oauth_codes, oauth_tokens from anon, authenticated;
revoke all on sequence magic_links_id_seq, oauth_codes_id_seq, oauth_tokens_id_seq from anon, authenticated;
