-- Credit purchases are USD expenses on the configured Apify account, not USDC wallet transfers.
-- Reserve the full cap before starting; retain it when an API response is ambiguous.
create table apify_runs (
    id bigint generated by default as identity primary key,
    agent_id bigint not null references agents(id),
    mandate_id bigint not null references mandates(id),
    actor text not null,
    input_hash text not null,
    reason text not null,
    max_charge bigint not null check (max_charge > 0),
    actual_charge bigint check (actual_charge >= 0),
    status text not null default 'STARTING',
    run_id text unique,
    dataset_id text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (agent_id, mandate_id, actor, input_hash)
);
create index apify_runs_agent on apify_runs(agent_id, created_at);
alter table apify_runs enable row level security;
revoke all on apify_runs from anon, authenticated;
