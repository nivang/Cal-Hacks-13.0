-- Price discovery. compare_prices (compare.py) ranks every service that could do one need of a task and recommends
-- the best value; each comparison is kept here, so the owner can see on the Tasks page what was compared and why one
-- was picked, and so the pricier_pick rule (intent.py) can hold a payment that costs more than the cheapest buyable
-- option the comparison found. offers holds every offer as shown (seller written names and the judge's reasons, so
-- server side only). buyable_keys are the URLs without their query that pay() could buy, for that rule's lookup.
-- agents.auto_buy_best_value is the owner's switch on the Rules page: on, the agent may buy the recommended best
-- value without asking even when it is the pricier option (every other check still runs); off, it is held.
-- RLS on with no policies and no grants, as in 004.

alter table agents add column auto_buy_best_value boolean not null default false;

create table price_comparisons (
    id bigint generated by default as identity primary key,
    mandate_id bigint not null references mandates (id),
    query text not null,
    calls integer not null check (calls > 0),
    results integer not null check (results > 0),
    offers jsonb not null,
    buyable_keys text[] not null default '{}',
    best_key text,
    best_name text,
    best_cost numeric(18,6),
    cheapest_key text,
    cheapest_name text,
    cheapest_cost numeric(18,6),
    explanation text not null,
    created_at timestamptz not null default now()
);

create index price_comparisons_mandate on price_comparisons (mandate_id, id desc);

alter table price_comparisons enable row level security;
revoke all on price_comparisons from anon, authenticated;
