-- What Sentinel is checking right now, for the Live page (sentinel/live.py). A payment's attempt row is written only
-- once the guard and the intent review have decided, so without this the owner sees nothing while the judge thinks.
-- One row per pay call or search preview in progress: stages is every step so far (the last one is running), and
-- attempt_id links the attempt once it exists, so the page shows the check instead of a half finished card. The row is
-- deleted when the call ends; a row not updated for two minutes is stale (the process died) and is ignored, then
-- cleared by the next check. Progress only: nothing reads it to decide a payment.
-- RLS on with no policies and no grants, as in 004.

create table live_checks (
    id bigint generated by default as identity primary key,
    agent_id bigint not null references agents (id),
    mandate_id bigint references mandates (id),
    kind text not null check (kind in ('pay', 'search')),
    url text not null,
    pay_to text,
    amount bigint check (amount is null or amount > 0),
    stages text[] not null,
    attempt_id bigint references payment_attempts (id),
    started_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
create index live_checks_agent_idx on live_checks (agent_id, updated_at);

alter table live_checks enable row level security;
revoke all on live_checks from anon, authenticated;
