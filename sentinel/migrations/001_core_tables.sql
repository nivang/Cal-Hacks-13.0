-- Sentinel core tables. Schema agnostic (no "public." prefix) so the same file builds the "test" schema.
-- Ids are bigint identity, not uuid: the code returns integer row ids to callers and writes them into
-- journal memos, and the SQLite data being migrated already has integer ids that must be preserved.
-- Money is numeric(18,6) in whole USDC (0.500000). The Python layer converts to and from atomic units.

create table accounts (
    id bigint generated by default as identity primary key,
    code text not null unique,
    name text not null,
    type text not null check (type in ('asset', 'expense', 'equity'))
);

create table agents (
    id bigint generated by default as identity primary key,
    name text not null unique,
    token_hash text,
    per_payment_cap numeric(18,6) not null check (per_payment_cap > 0),
    weekly_budget numeric(18,6) not null check (weekly_budget > 0),
    expense_account_id bigint not null references accounts (id)
);

create table sellers (
    id bigint generated by default as identity primary key,
    name text not null,
    pay_to text not null,
    network text not null,
    asset text not null,
    status text not null check (status in ('approved', 'pending', 'blocked')),
    added_by text not null,
    added_at timestamptz not null default now(),
    unique (pay_to, network, asset)
);

create table payment_attempts (
    id bigint generated by default as identity primary key,
    agent_id bigint not null references agents (id),
    url text not null,
    reason text,
    pay_to text,
    amount numeric(18,6) check (amount is null or amount > 0),
    quote_json jsonb,
    dedupe_key text,
    decision text,
    rule_fired text,
    status text not null check (status in ('blocked', 'pending', 'approved', 'denied', 'settled', 'failed')),
    tx_hash text,
    response_hash text,
    created_at timestamptz not null default now(),
    settled_at timestamptz
);
-- In flight lock: one live attempt per key, so two simultaneous identical calls cannot both pass.
create unique index one_inflight_per_key on payment_attempts (dedupe_key)
    where status in ('pending', 'approved');
-- A transaction can settle at most one attempt.
create unique index one_attempt_per_tx on payment_attempts (tx_hash) where tx_hash is not null;
-- Foreign key and lookup indexes.
create index payment_attempts_agent_created_idx on payment_attempts (agent_id, created_at);
create index payment_attempts_pay_to_settled_idx on payment_attempts (lower(pay_to), settled_at desc)
    where status = 'settled';

create table approvals (
    id bigint generated by default as identity primary key,
    attempt_id bigint not null references payment_attempts (id),
    approver text not null,
    decision text not null check (decision in ('approved', 'denied')),
    note text,
    decided_at timestamptz not null default now()
);
create index approvals_attempt_idx on approvals (attempt_id);

create table journal_entries (
    id bigint generated by default as identity primary key,
    attempt_id bigint references payment_attempts (id),
    reverses_entry_id bigint references journal_entries (id),
    date timestamptz not null default now(),
    memo text not null
);
create unique index one_entry_per_attempt on journal_entries (attempt_id)
    where attempt_id is not null and reverses_entry_id is null;
create index journal_entries_reverses_idx on journal_entries (reverses_entry_id)
    where reverses_entry_id is not null;

create table journal_lines (
    id bigint generated by default as identity primary key,
    entry_id bigint not null references journal_entries (id),
    account_id bigint not null references accounts (id),
    debit numeric(18,6) not null default 0 check (debit >= 0),
    credit numeric(18,6) not null default 0 check (credit >= 0),
    check ((debit = 0) <> (credit = 0))
);
create index journal_lines_entry_idx on journal_lines (entry_id);
create index journal_lines_account_idx on journal_lines (account_id);
create index agents_expense_account_idx on agents (expense_account_id);
