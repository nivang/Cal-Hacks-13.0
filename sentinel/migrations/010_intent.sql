-- Intent binding: every payment an agent makes through MCP belongs to a task, and is checked against what the owner
-- actually asked for, not only against the fixed rules in guard.py.
--
-- mandates: one row per task. The agent proposes it with start_task, in the owner's own words (task_text); Claude
-- turns those words into a goal, the kinds of purchases the task needs (expected_types) and what is clearly out of
-- scope. It is live at once as provisional, spending at most policy.json's intent_provisional_budget, until the owner
-- confirms it on the account page (confirmed, the full budget) or revokes it. A mandate expires at expires_at.
-- payment_attempts gains the intent facts of each payment: which mandate, where the agent says it found the link
-- (found_at), the seller's own description (quoted data), and which tier decided (0 rules, 1 fast check, 2 judge)
-- with its verdict and reason. Status escalated is a payment held for the owner: nothing was paid, and like blocked
-- it never takes the in flight lock (one_inflight_per_key covers pending and approved only).
-- intent_cache: the tier 1 verdict for one mandate, seller and URL, so a repeat purchase skips the model.
-- allowances: the owner's Allow once on a held payment. The next identical payment under the same mandate (same
-- seller, URL and amount) uses it up and goes through.
-- RLS on with no policies and no grants, as in 004: the task text stays server side. The new payment_attempts
-- columns fall under 005's table level read for dashboard viewers, like the reason column already does.

create table mandates (
    id bigint generated by default as identity primary key,
    agent_id bigint not null references agents (id),
    task_text text not null check (length(task_text) between 1 and 2000),
    goal text not null,
    expected_types text[] not null default '{}',
    out_of_scope text[] not null default '{}',
    budget numeric(18,6) not null check (budget > 0),
    per_call numeric(18,6) check (per_call is null or per_call > 0),
    status text not null default 'provisional' check (status in ('provisional', 'confirmed', 'revoked')),
    created_at timestamptz not null default now(),
    confirmed_at timestamptz,
    expires_at timestamptz not null
);
create index mandates_agent_created_idx on mandates (agent_id, created_at desc);

alter table payment_attempts
    add column mandate_id bigint references mandates (id),
    add column found_at text,
    add column seller_description text,
    add column intent_tier smallint check (intent_tier is null or intent_tier between 0 and 2),
    add column intent_verdict text,
    add column intent_reason text;
alter table payment_attempts drop constraint payment_attempts_status_check;
alter table payment_attempts add constraint payment_attempts_status_check
    check (status in ('blocked', 'pending', 'approved', 'denied', 'settled', 'failed', 'escalated', 'authorized', 'cancelled', 'expired'));
create index payment_attempts_mandate_created_idx on payment_attempts (mandate_id, created_at)
    where mandate_id is not null;

create table intent_cache (
    mandate_id bigint not null references mandates (id),
    pay_to text not null,  -- lower case, so 0xAbc and 0xabc share one verdict
    url text not null,
    verdict text not null check (verdict in ('fits', 'off_task', 'unsure')),
    reason text not null,
    created_at timestamptz not null default now(),
    primary key (mandate_id, pay_to, url)
);

create table allowances (
    id bigint generated by default as identity primary key,
    attempt_id bigint not null unique references payment_attempts (id),  -- the held payment the owner allowed
    granted_by uuid not null references users (id),
    created_at timestamptz not null default now(),
    expires_at timestamptz not null,
    used_at timestamptz,
    used_by_attempt_id bigint references payment_attempts (id)
);

alter table mandates enable row level security;
alter table intent_cache enable row level security;
alter table allowances enable row level security;
revoke all on mandates, intent_cache, allowances from anon, authenticated;
